"""Run the Stage 1 pipeline end to end and write reports/stage1_results.md.

python -m engine.run_stage1
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from engine import data
from engine import estimation as est
from engine.optimizer import (
    GroupConstraint,
    PortfolioProblem,
    efficient_frontier,
    max_sharpe,
    min_variance,
)
from engine.risk import risk_contributions

REPORTS_DIR = data.PROJECT_ROOT / "reports"

# Illustrative constraints, NOT calibrated to any insurer's investment policy.
ILLUSTRATIVE_GROUPS = [
    GroupConstraint("High yield cap", ["HYG"], 0.0, 0.10),
    GroupConstraint("Growth assets cap", ["SPY", "EFA", "EEM", "VNQ"], 0.0, 0.40),
]
ILLUSTRATIVE_BOUNDS = (0.0, 0.35)


def _pct(x: pd.DataFrame | pd.Series, digits: int = 2) -> pd.DataFrame | pd.Series:
    return (x * 100).round(digits)


def main() -> None:
    prices, report = data.clean_prices(data.load_prices())
    rets = data.monthly_returns(prices)
    assets = list(data.UNIVERSE)
    a = rets[assets]
    rf = float(rets[data.RISK_FREE_TICKER].mean() * est.PERIODS_PER_YEAR)

    cov_s = est.sample_covariance(a)
    cov_lw, d_lw = est.ledoit_wolf_covariance(a)
    cov, d_corr = est.ledoit_wolf_correlation_covariance(a)
    chk = est.check_covariance(cov)
    bs = est.bayes_stein_mean(a)

    unconstrained = PortfolioProblem(bs.mu, cov, risk_free_rate=rf)
    constrained = PortfolioProblem(
        bs.mu, cov, bounds=ILLUSTRATIVE_BOUNDS, groups=ILLUSTRATIVE_GROUPS, risk_free_rate=rf
    )

    results = {}
    for label, prob in [("Long-only", unconstrained), ("Constrained", constrained)]:
        for fn in (min_variance, max_sharpe):
            results[f"{label} {fn.__name__}"] = fn(prob)

    frontier = efficient_frontier(constrained, n_points=15)
    frontier.to_csv(REPORTS_DIR / "stage1_frontier_constrained.csv", index=False)

    weights = pd.DataFrame({k: r.weights for k, r in results.items()})
    summary = pd.DataFrame(
        {
            k: {"exp_return": r.expected_return, "volatility": r.volatility, "sharpe": r.sharpe, "solver_ok": r.success}
            for k, r in results.items()
        }
    )
    rc = risk_contributions(results["Constrained max_sharpe"].weights, cov)

    vols = pd.DataFrame(
        {
            "sample": np.sqrt(np.diag(cov_s)),
            "lw_raw": np.sqrt(np.diag(cov_lw)),
            "lw_corr (default)": np.sqrt(np.diag(cov)),
        },
        index=assets,
    )

    lines = [
        "# Stage 1 results",
        "",
        "Generated by `python -m engine.run_stage1`. Annualized figures, in percent.",
        "",
        f"- Data window: {report.common_start} to {report.end}, {len(a)} monthly returns, {len(assets)} assets",
        f"- Risk-free rate (BIL mean over window): {rf * 100:.2f}%",
        f"- Ledoit-Wolf shrinkage intensity: raw {d_lw:.4f}, correlation-space {d_corr:.4f}",
        f"- Covariance check (default): symmetric={chk.symmetric}, min eigenvalue={chk.min_eigenvalue:.2e}, "
        f"condition number={chk.condition_number:.0f}",
        f"- Bayes-Stein: shrinkage phi={bs.shrinkage:.4f}, target (min-variance portfolio mean)={bs.target * 100:.2f}%",
        f"- Illustrative constraints: per-asset bounds {ILLUSTRATIVE_BOUNDS}, "
        + ", ".join(f"{g.name} {g.assets} <= {g.upper:.0%}" for g in ILLUSTRATIVE_GROUPS),
        "",
        "## Expected returns: historical vs Bayes-Stein",
        "",
        _pct(pd.DataFrame({"historical": bs.historical, "bayes_stein": bs.mu})).to_markdown(),
        "",
        "## Volatility by covariance estimator",
        "",
        _pct(vols).to_markdown(),
        "",
        "## Portfolio summary",
        "",
        summary.T.assign(
            exp_return=lambda d: (d.exp_return.astype(float) * 100).round(2),
            volatility=lambda d: (d.volatility.astype(float) * 100).round(2),
            sharpe=lambda d: d.sharpe.astype(float).round(3),
        ).to_markdown(),
        "",
        "## Weights",
        "",
        _pct(weights, 1).to_markdown(),
        "",
        "## Risk contributions: constrained max Sharpe",
        "",
        rc.assign(
            weight=lambda d: (d.weight * 100).round(1),
            marginal=lambda d: (d.marginal * 100).round(2),
            contribution=lambda d: (d.contribution * 100).round(3),
            pct_contribution=lambda d: (d.pct_contribution * 100).round(1),
        ).to_markdown(),
        "",
        f"Sum of contributions: {rc.contribution.sum() * 100:.4f}%, "
        f"portfolio volatility: {results['Constrained max_sharpe'].volatility * 100:.4f}%",
        "",
        "## Constrained efficient frontier",
        "",
        _pct(frontier[["expected_return", "volatility"]])
        .assign(sharpe=frontier.sharpe.round(3), success=frontier.success)
        .to_markdown(index=False),
        "",
    ]
    out = REPORTS_DIR / "stage1_results.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
